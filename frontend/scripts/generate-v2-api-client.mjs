import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(frontendRoot, "..");
const specPath = path.join(repoRoot, "backend-rs", "openapi", "hms-v2.openapi.json");
const outputPath = path.join(frontendRoot, "src", "lib", "api", "v2", "generated", "client.js");
const checkOnly = process.argv.includes("--check");

const document = JSON.parse(fs.readFileSync(specPath, "utf8"));
const operations = collectOperations(document.paths || {});
const output = renderClient(operations);

if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    console.error("frontend/src/lib/api/v2/generated/client.js is not current. Run npm run api:v2:generate.");
    process.exit(1);
  }
  process.exit(0);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);

function collectOperations(paths) {
  const methods = new Set(["get", "post", "put", "patch", "delete"]);
  const result = [];

  Object.entries(paths).forEach(([routePath, pathItem]) => {
    Object.entries(pathItem || {}).forEach(([method, operation]) => {
      if (!methods.has(method) || !operation?.operationId) {
        return;
      }

      const pathParamNames = [...routePath.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
      const queryParamNames = (operation.parameters || [])
        .filter((param) => param.in === "query" && param.name)
        .map((param) => param.name);

      result.push({
        operationId: operation.operationId,
        method: method.toUpperCase(),
        path: routePath,
        pathParamNames,
        queryParamNames,
        hasBody: Boolean(operation.requestBody),
      });
    });
  });

  return result.sort((a, b) => a.operationId.localeCompare(b.operationId));
}

function renderClient(operations) {
  const operationsById = Object.fromEntries(
    operations.map((operation) => [operation.operationId, operation]),
  );
  const operationsLiteral = JSON.stringify(operationsById, null, 2);
  const methods = operations
    .map((operation) => `    ${operation.operationId}: createOperation(request, operations.${operation.operationId}),`)
    .join("\n");

  return `// Generated by scripts/generate-v2-api-client.mjs. Do not edit by hand.

export const operations = ${operationsLiteral};

export function createGeneratedClient(request) {
  return {
${methods}
  };
}

function createOperation(request, operation) {
  return function generatedOperation(firstArg = {}, secondArg = {}, thirdArg = {}) {
    const normalized = normalizeArgs(operation, firstArg, secondArg, thirdArg);
    return request({
      method: operation.method,
      path: operation.path,
      pathParams: normalized.pathParams,
      query: normalized.query,
      body: normalized.body,
      signal: normalized.signal,
      headers: normalized.headers,
    });
  };
}

function normalizeArgs(operation, firstArg, secondArg, thirdArg) {
  if (operation.pathParamNames.length > 0 && operation.hasBody) {
    return {
      pathParams: firstArg || {},
      body: secondArg,
      ...pickOptions(thirdArg),
    };
  }

  if (operation.pathParamNames.length > 0) {
    return {
      pathParams: firstArg || {},
      ...pickOptions(secondArg),
    };
  }

  if (operation.hasBody) {
    return {
      body: firstArg,
      ...pickOptions(secondArg),
    };
  }

  return pickOptions(firstArg);
}

function pickOptions(options = {}) {
  return {
    query: options.query,
    signal: options.signal,
    headers: options.headers,
  };
}
`;
}
