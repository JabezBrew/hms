import User from 'lucide-react/dist/esm/icons/user.js';
import Heart from 'lucide-react/dist/esm/icons/heart.js';
import ClipboardList from 'lucide-react/dist/esm/icons/clipboard-list.js';
import FileCheck from 'lucide-react/dist/esm/icons/file-check.js';
import Calendar from 'lucide-react/dist/esm/icons/calendar.js';
import { Badge } from '@/components/ui/badge';

import { Layout } from '@/components/layout/layout';
import { PageHeader } from '@/shared/components/page/PageHeader';
import { PageShell } from '@/shared/components/page/PageShell';
import { usePageMeta } from '@/shared/hooks/usePageMeta';
import { useShiftHandoffPageController } from './shift-handoff/useShiftHandoffPageController';
import { ShiftHandoffProgress } from './shift-handoff/ShiftHandoffProgress';
import { ShiftHandoffStepContent } from './shift-handoff/ShiftHandoffStepContent';
import { ShiftHandoffStepPanel } from './shift-handoff/ShiftHandoffStepPanel';
import { ShiftHandoffNavigation } from './shift-handoff/ShiftHandoffNavigation';

const STEPS = [
  { id: 1, key: 'patient', title: 'Select Patient', icon: User },
  { id: 2, key: 'clinical', title: 'Clinical Info', icon: Heart },
  { id: 3, key: 'tasks', title: 'Tasks & Events', icon: ClipboardList },
  { id: 4, key: 'review', title: 'Review & Submit', icon: FileCheck },
];

export default function ShiftHandoffPage() {
  const {
    currentStep,
    selectedPatient,
    searchTerm,
    isAutoGenerated,
    formData,
    patients,
    patientsLoading,
    nurses,
    nursesLoading,
    usesDirectoryFallback,
    todayLabel,
    isSubmitting,
    handleSelectPatient,
    handleFieldChange,
    handleSearchChange,
    isStepComplete,
    goToStep,
    handleNext,
    handleBack,
    handleCancel,
    handleSubmit,
  } = useShiftHandoffPageController();

  const currentStepDef = STEPS.find(s => s.id === currentStep);

  const pageMeta = usePageMeta({
    title: 'Shift Handoff | HMS',
    breadcrumbs: [
      { label: 'Nursing', href: '/dashboards/nurse' },
      { label: 'Shift Handoff' },
    ],
  });

  return (
    <Layout>
      <PageShell>
        {pageMeta}
        <PageHeader
          title="Shift Handoff"
          description="Document and transfer patient care to the next shift"
          actions={(
            <Badge variant="outline" className="font-mono text-sm px-4 py-2">
              <Calendar className="mr-2 size-4" />
              {todayLabel}
            </Badge>
          )}
          size="lg"
        />

        <div className="container mx-auto px-4 py-6 max-w-4xl">
          <ShiftHandoffProgress
            steps={STEPS}
            currentStep={currentStep}
            isStepComplete={isStepComplete}
            onStepSelect={goToStep}
          />

          <ShiftHandoffStepPanel
            currentStepDef={currentStepDef}
            currentStep={currentStep}
            totalSteps={STEPS.length}
          >
            <ShiftHandoffStepContent
              currentStep={currentStep}
              patients={patients}
              patientsLoading={patientsLoading}
              selectedPatient={selectedPatient}
              onSelectPatient={handleSelectPatient}
              searchTerm={searchTerm}
              onSearchChange={handleSearchChange}
              formData={formData}
              onFieldChange={handleFieldChange}
              nurses={nurses}
              nursesLoading={nursesLoading}
              isAutoGenerated={isAutoGenerated}
              nurseScopeNotice={usesDirectoryFallback
                ? 'Ward-specific nurse assignments are not available for this deployment yet. Choose from active staff.'
                : null}
            />
          </ShiftHandoffStepPanel>

          <ShiftHandoffNavigation
            currentStep={currentStep}
            canSubmit={!!formData.to_nurse}
            isSubmitting={isSubmitting}
            onBack={handleBack}
            onCancel={handleCancel}
            onNext={handleNext}
            onSubmit={handleSubmit}
          />
        </div>
      </PageShell>
    </Layout>
  );
}
