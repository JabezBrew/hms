import { useState } from 'react';
import { Label } from '@/components/ui/label';
import { Textarea } from '@/components/ui/textarea';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import {
  Collapsible,
  CollapsibleContent,
  CollapsibleTrigger,
} from '@/components/ui/collapsible';
import { ClipboardList, Calendar, FileText, Users, Sparkles, ChevronDown, ChevronRight } from 'lucide-react';
import { cn } from '@/lib/utils';

/**
 * TasksEventsStep - Pending tasks, events, and care plan
 */
export function TasksEventsStep({
  formData,
  onChange,
  selectedPatient,
  isAutoGenerated = false
}) {
  const [showOptionalFields, setShowOptionalFields] = useState(false);

  // Check if optional fields have content
  const hasOptionalContent = formData.care_plan_updates || formData.family_updates;

  return (
    <div className="space-y-6">
      {/* Pending Tasks */}
      <div className="space-y-2">
        <div className="flex items-center justify-between">
          <Label className="font-mono text-xs uppercase tracking-wider text-muted-foreground">
            <ClipboardList className="inline h-3 w-3 mr-1" />
            Pending Tasks *
          </Label>
          {isAutoGenerated && formData.pending_tasks && (
            <Badge variant="outline" className="font-mono text-[10px] text-sky-600 border-sky-500/30 bg-sky-500/5">
              <Sparkles className="h-3 w-3 mr-1" />
              Auto-generated
            </Badge>
          )}
        </div>
        <p className="text-xs text-muted-foreground mb-2">
          Tasks to be completed: scheduled procedures, labs, medications due
        </p>
        <Textarea
          placeholder="List pending tasks..."
          value={formData.pending_tasks}
          onChange={(e) => onChange('pending_tasks', e.target.value)}
          rows={5}
          className="font-mono text-sm"
        />
      </div>

      {/* Key Events */}
      <div className="space-y-2">
        <Label className="font-mono text-xs uppercase tracking-wider text-muted-foreground">
          <Calendar className="inline h-3 w-3 mr-1" />
          Key Events This Shift
        </Label>
        <p className="text-xs text-muted-foreground mb-2">
          Significant events: falls, code responses, procedures, consultations
        </p>
        <Textarea
          placeholder="Document significant events..."
          value={formData.key_events}
          onChange={(e) => onChange('key_events', e.target.value)}
          rows={3}
          className="font-mono text-sm"
        />
      </div>

      {/* Optional Fields - Collapsible */}
      <Collapsible
        open={showOptionalFields || hasOptionalContent}
        onOpenChange={setShowOptionalFields}
      >
        <CollapsibleTrigger asChild>
          <Button
            variant="ghost"
            className="w-full justify-between font-mono text-xs uppercase tracking-wider text-muted-foreground hover:text-foreground"
          >
            <span className="flex items-center gap-2">
              {showOptionalFields || hasOptionalContent ? (
                <ChevronDown className="h-4 w-4" />
              ) : (
                <ChevronRight className="h-4 w-4" />
              )}
              Additional Fields (Optional)
            </span>
            {hasOptionalContent && (
              <Badge variant="secondary" className="font-mono text-[10px]">
                Has content
              </Badge>
            )}
          </Button>
        </CollapsibleTrigger>

        <CollapsibleContent className="space-y-6 pt-4">
          {/* Care Plan Updates */}
          <div className="space-y-2">
            <Label className="font-mono text-xs uppercase tracking-wider text-muted-foreground">
              <FileText className="inline h-3 w-3 mr-1" />
              Care Plan Updates
            </Label>
            <p className="text-xs text-muted-foreground mb-2">
              Changes to care plan, goals, or expected discharge timeline
            </p>
            <Textarea
              placeholder="Note any care plan changes..."
              value={formData.care_plan_updates}
              onChange={(e) => onChange('care_plan_updates', e.target.value)}
              rows={3}
              className="font-mono text-sm"
            />
          </div>

          {/* Family Updates */}
          <div className="space-y-2">
            <Label className="font-mono text-xs uppercase tracking-wider text-muted-foreground">
              <Users className="inline h-3 w-3 mr-1" />
              Family Updates
            </Label>
            <p className="text-xs text-muted-foreground mb-2">
              Family visits, concerns raised, or communications needed
            </p>
            <Textarea
              placeholder="Note family updates..."
              value={formData.family_updates}
              onChange={(e) => onChange('family_updates', e.target.value)}
              rows={3}
              className="font-mono text-sm"
            />
          </div>
        </CollapsibleContent>
      </Collapsible>
    </div>
  );
}
